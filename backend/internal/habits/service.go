func (s *service) Dashboard(ctx context.Context, userID uuid.UUID, today string) (Dashboard, error) {
	snap, err := s.load(ctx, userID, today, WindowMonth)
	if err != nil {
		return Dashboard{}, err
	}

	d := Dashboard{Date: DayKey(snap.today)}

	active := make([]HabitView, 0, len(snap.habits))
	paused := make([]HabitView, 0)
	for _, h := range snap.habits {
		v := s.view(h, snap)
		if h.State == StatePaused {
			paused = append(paused, v)
			continue
		}
		active = append(active, v)
	}
	d.Habits, d.Paused = active, paused
	d.Empty = len(active) == 0 && len(paused) == 0
	if d.Empty {
		d.Templates = Templates
		return d, nil
	}

	// Today's ring counts only what is actually due today. A weekday-only habit must not
	// make Saturday read as 5/8 when only five were ever scheduled.
	byslot := map[string]*SlotGroup{}
	for _, v := range active {
		if !v.ScheduledOn(snap.today) {
			continue
		}
		d.TotalToday++
		if v.Stats.TodayStatus == StatusDone {
			d.DoneToday++
		}
		g, ok := byslot[v.Slot]
		if !ok {
			meta := slotMeta[v.Slot]
			g = &SlotGroup{Slot: v.Slot, Label: meta.Label, Icon: meta.Icon}
			byslot[v.Slot] = g
		}
		g.Total++
		if v.Stats.TodayStatus == StatusDone {
			g.Done++
		}
		g.Habits = append(g.Habits, v)
	}
	for _, slot := range SlotOrder {
		if g, ok := byslot[slot]; ok {
			d.Slots = append(d.Slots, *g)
		}
	}
	if d.TotalToday > 0 {
		d.Percent = float64(d.DoneToday) / float64(d.TotalToday)
	}

	d.CurrentStreak, d.LongestStreak = AccountStreak(snap.rolls)
	d.Consistency = ConsistencyScore(Rate(snap.rolls), d.CurrentStreak)
	if n := len(snap.rolls); n > 7 {
		d.Week = snap.rolls[n-7:]
	} else {
		d.Week = snap.rolls
	}
	d.Nudge = buildNudge(active, snap.today, d.DoneToday, d.TotalToday, d.CurrentStreak)
	return d, nil
}

// buildNudge picks the single most useful thing to say right now.
//
// Ordered by how actionable it is, not by how impressive it sounds: a habit still open
// with a streak worth protecting beats a generic "you're doing great", and an all-done
// day gets a full stop rather than an invented next task.
func buildNudge(habits []HabitView, today time.Time, done, total, streak int) *Nudge {
	if total == 0 {
		return nil
	}
	if done == total {
		return &Nudge{Text: "Perfect day — every habit complete. Rest is part of the practice."}
	}

	// The open habit with the longest live streak: the one with most to lose today.
	var atRisk *HabitView
	openEvening := 0
	var lastEvening *HabitView
	for i := range habits {
		h := &habits[i]
		if !h.ScheduledOn(today) || h.Stats.TodayStatus == StatusDone || h.Stats.TodayStatus == StatusSkipped {
			continue
		}
		if h.Slot == SlotEvening {
			openEvening++
			lastEvening = h
		}
		if atRisk == nil || h.Stats.Current > atRisk.Stats.Current {
			atRisk = h
		}
	}
	if atRisk == nil {
		return nil
	}
	if atRisk.Stats.Current >= 3 {
		return &Nudge{
			Text:    atRisk.Name + " is still open, and it is carrying a " + plural(atRisk.Stats.Current, "day") + " streak. Worth protecting before the day closes.",
			Action:  "Complete now",
			HabitID: atRisk.ID,
		}
	}
	if openEvening == 1 && lastEvening != nil && lastEvening.ReminderTime == "" {
		return &Nudge{
			Text:    lastEvening.Name + " is your only evening habit still open. Want a gentle nudge at " + defaultTime(lastEvening.TimeLocal, "18:00") + " so it does not slip?",
			Action:  "Set reminder",
			HabitID: lastEvening.ID,
		}
	}
	remaining := total - done
	return &Nudge{
		Text:    plural(remaining, "habit") + " left today. " + streakLine(streak),
		Action:  "Complete now",
		HabitID: atRisk.ID,
	}
}

func streakLine(streak int) string {
	if streak <= 1 {
		return "Starting again is the whole skill."
	}
	return "Finish strong — you are on a " + plural(streak, "day") + " run."
}

func defaultTime(v, fallback string) string {
	if strings.TrimSpace(v) == "" {
		return fallback
	}
	return v
}

func plural(n int, unit string) string {
	if n == 1 {
		return "1 " + unit
	}
	return itoa(n) + " " + unit + "s"
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var buf [20]byte
	i := len(buf)
	for n > 0 {
		i--
		buf[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		buf[i] = '-'
	}
	return string(buf[i:])
}

