// snapshot is the loaded-and-derived state every read model starts from.
type snapshot struct {
	today   time.Time
	habits  []Habit // active + paused, sorted for display
	all     []Habit // including archived, for statistics
	entries EntryIndex
	stats   map[string]HabitStats
	rolls   []DayRoll // [today-window, today]
}

func (s *service) load(ctx context.Context, userID uuid.UUID, todayKey string, windowDays int) (snapshot, error) {
	snap := snapshot{today: s.resolveToday(todayKey)}

	all, err := s.store.Habits(ctx, userID)
	if err != nil {
		return snap, err
	}
	snap.all = all

	from := DayKey(dayFromNumber(dayNumber(snap.today) - windowDays))
	to := DayKey(snap.today)
	entries, err := s.store.EntriesBetween(ctx, userID, from, to)
	if err != nil {
		return snap, err
	}
	snap.entries = IndexEntries(entries)

	snap.stats = make(map[string]HabitStats, len(all))
	for _, h := range all {
		snap.stats[h.ID] = ComputeHabitStats(h, snap.entries.For(h.ID), snap.today)
	}

	snap.habits = make([]Habit, 0, len(all))
	for _, h := range all {
		if h.State != StateArchived {
			snap.habits = append(snap.habits, h)
		}
	}
	sortHabits(snap.habits)

	snap.rolls = RollDays(snap.all, snap.entries,
		dayFromNumber(dayNumber(snap.today)-windowDays), snap.today)
	return snap, nil
}

// resolveToday takes the client's local day when it sent one. The server's own date is
// only a fallback: a user in Tashkent finishing a habit at 01:00 must have it counted on
// their day, not on the UTC day that ended an hour ago.
func (s *service) resolveToday(key string) time.Time {
	if t, ok := ParseDay(key); ok {
		return t
	}
	return s.now().Truncate(24 * time.Hour)
}

// sortHabits puts the list in the order the home screen renders: the user's own
// sortIndex first, then creation order, then id so the result is deterministic.
func sortHabits(hs []Habit) {
	sort.SliceStable(hs, func(i, j int) bool {
		if hs[i].SortIndex != hs[j].SortIndex {
			return hs[i].SortIndex < hs[j].SortIndex
		}
		if hs[i].CreatedAt != hs[j].CreatedAt {
			return hs[i].CreatedAt < hs[j].CreatedAt
		}
		return hs[i].ID < hs[j].ID
	})
}

func (s *service) view(h Habit, snap snapshot) HabitView {
	return HabitView{Habit: h, Category: CategoryByID(h.CategoryID), Stats: snap.stats[h.ID]}
}

