func (s *service) Detail(ctx context.Context, userID uuid.UUID, habitID, today string) (Detail, error) {
	var d Detail
	h, err := s.store.Habit(ctx, userID, habitID)
	if err != nil {
		return d, err
	}
	now := s.resolveToday(today)

	entries, err := s.store.EntriesForHabit(ctx, userID, habitID)
	if err != nil {
		return d, err
	}
	idx := IndexEntries(entries)
	byDay := idx.For(habitID)

	st := ComputeHabitStats(h, byDay, now)
	d.Habit = HabitView{Habit: h, Category: CategoryByID(h.CategoryID), Stats: st}

	// Contribution grid: whole weeks so the columns line up, ending on today's week.
	days := DetailWeeks * 7
	// Start on the Monday that makes today fall in the last column.
	end := dayNumber(now) + (6 - WeekdayIndex(now))
	start := end - days + 1
	rolls := RollDays([]Habit{h}, idx, dayFromNumber(start), dayFromNumber(end))
	d.HeatmapFrom = DayKey(dayFromNumber(start))
	d.Heatmap = make([]int, 0, len(rolls))
	todayNum := dayNumber(now)
	for i, r := range rolls {
		if start+i > todayNum {
			d.Heatmap = append(d.Heatmap, -1) // future: rendered as an outline, not a miss
			continue
		}
		d.Heatmap = append(d.Heatmap, r.Level)
	}

	// This week, Monday → Sunday.
	weekStart := dayNumber(now) - WeekdayIndex(now)
	for i := 0; i < 7; i++ {
		key := DayKey(dayFromNumber(weekStart + i))
		if e, ok := byDay[key]; ok && e.Status == StatusDone {
			d.Week = append(d.Week, 1)
			continue
		}
		d.Week = append(d.Week, 0)
	}

	monthRolls := RollDays([]Habit{h}, idx, dayFromNumber(dayNumber(now)-181), now)
	d.Months, d.MonthLabels = MonthlyRates(monthRolls, now, 6)

	first := time.Date(now.Year(), now.Month(), 1, 0, 0, 0, 0, time.UTC)
	d.Month = RollDays([]Habit{h}, idx, first, lastOfMonth(first))

	for _, m := range []int{7, 30, 100, 365} {
		d.Milestones = append(d.Milestones, Milestone{Days: m, Reached: st.Longest >= m, Have: st.Longest})
	}

	notes, err := s.store.Notes(ctx, userID, habitID)
	if err != nil {
		return d, err
	}
	sort.Slice(notes, func(i, j int) bool { return notes[i].CreatedAt > notes[j].CreatedAt })
	d.Notes = notes
	return d, nil
}

func lastOfMonth(first time.Time) time.Time {
	return first.AddDate(0, 1, -1)
}

