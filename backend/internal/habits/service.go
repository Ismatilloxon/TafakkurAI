func (s *service) Board(ctx context.Context, userID uuid.UUID, today string) (AchievementBoard, error) {
	snap, err := s.load(ctx, userID, today, WindowYear)
	if err != nil {
		return AchievementBoard{}, err
	}
	stored, err := s.store.Achievements(ctx, userID)
	if err != nil {
		return AchievementBoard{}, err
	}

	facts := AchievementFacts{HabitCount: len(snap.habits)}
	for _, h := range snap.all {
		st := snap.stats[h.ID]
		if st.Longest > facts.BestStreak {
			facts.BestStreak = st.Longest
		}
		switch {
		case h.TimeLocal != "" && h.TimeLocal < "08:00":
			facts.MorningDone += st.Done
		case h.TimeBucket() == "Evening" || h.TimeBucket() == "Night":
			facts.EveningDone += st.Done
		}
	}
	monthFrom := dayNumber(snap.today) - WindowMonth
	month := make([]DayRoll, 0, WindowMonth+1)
	for _, r := range snap.rolls {
		if d, ok := ParseDay(r.Date); ok && dayNumber(d) >= monthFrom {
			month = append(month, r)
		}
	}
	facts.MonthRate = Rate(month)
	facts.PerfectRun = LongestPerfectRun(snap.rolls)
	facts.DaysSinceMiss = DaysSinceMiss(snap.rolls)

	now := s.now()
	items := EvaluateAchievements(facts, stored, now)

	// Persist only what just crossed the line. Writing all twelve on every request would
	// bump twelve `seq` values and hand every other device a pointless delta pull.
	for _, v := range NewlyUnlocked(items, stored) {
		_, _ = s.store.Put(ctx, userID, EntityAchievement, v.ID, AchievementState{
			ID:         v.ID,
			UnlockedAt: v.UnlockedAt,
			Progress:   1,
			UpdatedAt:  now.UnixMilli(),
		}, now)
	}

	board := AchievementBoard{Total: len(items), Items: items, BestStrek: facts.BestStreak}
	for _, v := range items {
		if v.Unlocked {
			board.Unlocked++
		}
	}
	board.Headline = "Keep the fire."
	if board.Unlocked == 0 {
		board.Headline = "Your first badge is close."
	}
	board.Subtitle = boardSubtitle(facts.BestStreak, items)
	return board, nil
}

func boardSubtitle(bestStreak int, items []AchievementView) string {
	near := 0
	for _, v := range items {
		if !v.Unlocked && v.Progress >= 0.6 {
			near++
		}
	}
	if bestStreak == 0 {
		return "Complete one habit today and the first badge is yours."
	}
	if near == 0 {
		return "You are " + plural(bestStreak, "day") + " deep. Keep going."
	}
	return "You are " + plural(bestStreak, "day") + " deep. " + plural(near, "milestone") + " within reach."
}

