// Service assembles the read models and applies the write operations.
//
// Every read follows the same three steps — load the habits, load the entry window,
// derive — and derives with the pure functions in stats.go. Nothing is cached and nothing
// is denormalised: a streak is always recomputed from entries, so an entry that arrives
// six days late lands in the right run instead of being lost to a stale counter.
type Service interface {
	Dashboard(ctx context.Context, userID uuid.UUID, today string) (Dashboard, error)
	Detail(ctx context.Context, userID uuid.UUID, habitID, today string) (Detail, error)
	Statistics(ctx context.Context, userID uuid.UUID, today string) (Statistics, error)
	Calendar(ctx context.Context, userID uuid.UUID, month, today string) (CalendarView, error)
	Board(ctx context.Context, userID uuid.UUID, today string) (AchievementBoard, error)

	Save(ctx context.Context, userID uuid.UUID, in HabitInput) (HabitView, error)
	Delete(ctx context.Context, userID uuid.UUID, habitID string) error
	SetState(ctx context.Context, userID uuid.UUID, habitID, state, pausedUntil string) (HabitView, error)
	Reorder(ctx context.Context, userID uuid.UUID, ids []string) error

	RecordEntry(ctx context.Context, userID uuid.UUID, in EntryInput) (EntryResult, error)
	AddNote(ctx context.Context, userID uuid.UUID, habitID, dateKey, text string) (Note, error)
	DeleteNote(ctx context.Context, userID uuid.UUID, noteID string) error
}

type service struct {
	store *Store
	now   func() time.Time
}

func NewService(store *Store) Service {
	return &service{store: store, now: func() time.Time { return time.Now().UTC() }}
}

