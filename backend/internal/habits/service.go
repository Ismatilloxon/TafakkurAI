func (s *service) Statistics(ctx context.Context, userID uuid.UUID, today string) (Statistics, error) {
	snap, err := s.load(ctx, userID, today, WindowYear)
	if err != nil {
		return Statistics{}, err
	}
	var out Statistics

	monthFrom := dayNumber(snap.today) - WindowMonth
	month := make([]DayRoll, 0, WindowMonth+1)
	for _, r := range snap.rolls {
		if d, ok := ParseDay(r.Date); ok && dayNumber(d) >= monthFrom {
			month = append(month, r)
		}
	}

	out.Completion = Rate(month)
	out.Current, out.Longest = AccountStreak(snap.rolls)
	out.Consistency = ConsistencyScore(out.Completion, out.Current)

	doneTotal, days := 0, 0
	for _, r := range month {
		doneTotal += r.Done
		out.Skipped += r.Skipped
		out.Missed += r.Scheduled - r.Done
		if r.Scheduled > 0 || r.Skipped > 0 {
			days++
		}
	}
	if days > 0 {
		out.AvgPerDay = math.Round(float64(doneTotal)/float64(days)*10) / 10
	}

	weekday, best, worst := WeekdayRates(snap.rolls)
	out.Weekday = weekday[:]
	out.BestDay, out.WorstDay = WeekdayNames[best], WeekdayNames[worst]

	out.Months, out.MonthLabels = MonthlyRates(snap.rolls, snap.today, 6)

	out.YearFrom = DayKey(dayFromNumber(dayNumber(snap.today) - WindowYear + 1))
	out.Year = make([]int, 0, len(snap.rolls))
	for _, r := range snap.rolls {
		out.Year = append(out.Year, r.Level)
	}

	// Category / radar / time-of-day read the LIFETIME per-habit stats rather than the
	// window, because a "by category" bar that silently means "last 53 weeks" would
	// disagree with the same number on the habit detail screen.
	out.ByCategory = CategoryRates(snap.all, snap.stats)
	out.Radar = RadarValues(snap.all, snap.stats)
	out.TimeOfDay = TimeOfDayRates(snap.all, snap.stats)
	out.Headline = statsHeadline(out.Completion, out.Current)
	return out, nil
}

func statsHeadline(rate float64, streak int) string {
	switch {
	case rate >= 0.9:
		return "An outstanding month."
	case rate >= 0.75:
		return "A strong month."
	case rate >= 0.5:
		return "A steady month."
	case streak > 0:
		return "Back on track."
	default:
		return "A fresh start."
	}
}

