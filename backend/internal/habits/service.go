// HabitInput is a create or an update. Every pointer field means "leave unchanged", which
// is what lets the reminder sheet PATCH one field without shipping the whole habit and
// racing the edit screen.
type HabitInput struct {
	ID          string
	Name        *string
	Description *string
	CategoryID  *string
	ColorKey    *string
	Icon        *string
	Slot        *string
	TimeLocal   *string
	Reminder    *bool
	ReminderAt  *string
	SmartTiming *bool
	Frequency   *string
	Weekdays    *[]int
	Difficulty  *string
	GoalType    *string
	GoalTarget  *int
	GoalUnit    *string
	Motivation  *string
	SortIndex   *int
}

func (s *service) Save(ctx context.Context, userID uuid.UUID, in HabitInput) (HabitView, error) {
	now := s.now()
	nowMs := now.UnixMilli()

	existing, err := s.store.Habit(ctx, userID, in.ID)
	creating := err == ErrNotFound
	if err != nil && !creating {
		return HabitView{}, err
	}
	if creating {
		if in.ID == "" || in.Name == nil || strings.TrimSpace(*in.Name) == "" {
			return HabitView{}, ErrInvalidInput
		}
		existing = Habit{ID: in.ID, CreatedAt: nowMs, State: StateActive, Frequency: FrequencyDaily, GoalType: GoalCheck, GoalTarget: 1}
		// New habits land at the top, matching where the client optimistically inserts
		// them. Negative indices are fine: sortHabits only compares.
		existing.SortIndex = int(-(nowMs / 1000))
	}

	h := existing
	applyString(&h.Name, in.Name)
	applyString(&h.Description, in.Description)
	applyString(&h.CategoryID, in.CategoryID)
	applyString(&h.ColorKey, in.ColorKey)
	applyString(&h.Icon, in.Icon)
	applyString(&h.Slot, in.Slot)
	applyString(&h.TimeLocal, in.TimeLocal)
	applyString(&h.ReminderTime, in.ReminderAt)
	applyString(&h.Frequency, in.Frequency)
	applyString(&h.Difficulty, in.Difficulty)
	applyString(&h.GoalType, in.GoalType)
	applyString(&h.GoalUnit, in.GoalUnit)
	applyString(&h.Motivation, in.Motivation)
	if in.Reminder != nil {
		h.ReminderEnabled = Bool(*in.Reminder)
	}
	if in.SmartTiming != nil {
		h.SmartTiming = Bool(*in.SmartTiming)
	}
	if in.Weekdays != nil {
		h.Weekdays = IntList(*in.Weekdays)
	}
	if in.GoalTarget != nil {
		h.GoalTarget = *in.GoalTarget
	}
	if in.SortIndex != nil {
		h.SortIndex = *in.SortIndex
	}
	h.UpdatedAt = nowMs
	h.Normalize()
	if h.Name == "" {
		return HabitView{}, ErrInvalidInput
	}

	if err := s.writeHabit(ctx, userID, h, now); err != nil {
		return HabitView{}, err
	}

	entries, err := s.store.EntriesForHabit(ctx, userID, h.ID)
	if err != nil {
		return HabitView{}, err
	}
	today := s.resolveToday("")
	st := ComputeHabitStats(h, IndexEntries(entries).For(h.ID), today)
	return HabitView{Habit: h, Category: CategoryByID(h.CategoryID), Stats: st}, nil
}

// writeHabit persists through Patch so fields a newer client added survive a server-side
// edit. The typed struct provides the values; the raw map provides everything else.
func (s *service) writeHabit(ctx context.Context, userID uuid.UUID, h Habit, now time.Time) error {
	blob, err := json.Marshal(h)
	if err != nil {
		return err
	}
	var known map[string]json.RawMessage
	if err := json.Unmarshal(blob, &known); err != nil {
		return err
	}
	err = s.store.Patch(ctx, userID, EntityHabit, h.ID, now, func(fields map[string]json.RawMessage) error {
		for k, v := range known {
			fields[k] = v
		}
		return nil
	})
	if err == ErrNotFound {
		_, err = s.store.Put(ctx, userID, EntityHabit, h.ID, h, now)
	}
	return err
}

func applyString(dst *string, src *string) {
	if src != nil {
		*dst = strings.TrimSpace(*src)
	}
}

// Delete tombstones the habit. Its entries and notes are left in place deliberately: they
// are already invisible (nothing lists an orphan entry) and keeping them means an "undo
// delete" is a single write rather than an unrecoverable cascade.
func (s *service) Delete(ctx context.Context, userID uuid.UUID, habitID string) error {
	if _, err := s.store.Habit(ctx, userID, habitID); err != nil {
		return err
	}
	return s.store.Tombstone(ctx, userID, EntityHabit, habitID, s.now())
}

func (s *service) SetState(ctx context.Context, userID uuid.UUID, habitID, state, pausedUntil string) (HabitView, error) {
	h, err := s.store.Habit(ctx, userID, habitID)
	if err != nil {
		return HabitView{}, err
	}
	now := s.now()
	h.State = NormalizeState(state)
	h.PausedUntil = ""
	if h.State == StatePaused {
		h.PausedUntil = pausedUntil
	}
	h.UpdatedAt = now.UnixMilli()
	if err := s.writeHabit(ctx, userID, h, now); err != nil {
		return HabitView{}, err
	}
	entries, err := s.store.EntriesForHabit(ctx, userID, habitID)
	if err != nil {
		return HabitView{}, err
	}
	st := ComputeHabitStats(h, IndexEntries(entries).For(habitID), s.resolveToday(""))
	return HabitView{Habit: h, Category: CategoryByID(h.CategoryID), Stats: st}, nil
}

// Reorder writes the whole ordered list at once. Last-writer-wins on the list as a unit,
// which is the only sane answer: two devices that each dragged a different row have no
// meaningful merge, and picking one order is better than inventing a third.
func (s *service) Reorder(ctx context.Context, userID uuid.UUID, ids []string) error {
	if len(ids) == 0 {
		return nil
	}
	habits, err := s.store.Habits(ctx, userID)
	if err != nil {
		return err
	}
	byID := make(map[string]Habit, len(habits))
	for _, h := range habits {
		byID[h.ID] = h
	}
	now := s.now()
	payloads := make(map[string]any, len(ids))
	for i, id := range ids {
		h, ok := byID[id]
		if !ok {
			continue
		}
		h.SortIndex = i
		h.UpdatedAt = now.UnixMilli()
		payloads[id] = h
	}
	return s.store.PutMany(ctx, userID, EntityHabit, payloads, now)
}

// EntryInput is one completion, skip, partial increment or undo.
type EntryInput struct {
	HabitID string
	DateKey string
	Op      string // complete | undo | skip | progress
	Value   int
	Reason  string
}

const (
	OpComplete = "complete"
	OpUndo     = "undo"
	OpSkip     = "skip"
	OpProgress = "progress"
)

// EntryResult reports what the row now says, plus the recomputed stats so the client can
// update its ring without a second request.
type EntryResult struct {
	Entry   *Entry     `json:"entry"`
	Stats   HabitStats `json:"stats"`
	Removed bool       `json:"removed"`
}

// RecordEntry is the write behind every tap on a completion button.
//
// It is idempotent on (habitId, dateKey) because the row id is derived from the pair —
// replaying the same op lands on the same row and leaves it in the same state. That is
// what makes the client's outbox safe to retry after a timeout it never saw the answer to.
func (s *service) RecordEntry(ctx context.Context, userID uuid.UUID, in EntryInput) (EntryResult, error) {
	return s.recordEntry(ctx, s.store, userID, in, false)
}

type entryProjector func(context.Context, pgx.Tx, EntryResult) error

// recordEntryAtomic is the REST integration boundary. The source entity_state row and
// every projector invoked by the handler use the same caller-owned PostgreSQL
// transaction; no source row is committed when progression or its tracker mirror fails.
// It remains outside Service so read-model consumers and existing fakes keep the narrow
// public API and cannot accidentally take ownership of a transaction.
func (s *service) recordEntryAtomic(
	ctx context.Context,
	userID uuid.UUID,
	in EntryInput,
	project entryProjector,
) (EntryResult, error) {
	tx, err := s.store.begin(ctx)
	if err != nil {
		return EntryResult{}, fmt.Errorf("begin habit entry: %w", err)
	}
	defer func() { _ = tx.Rollback(ctx) }()

	res, err := s.recordEntry(ctx, s.store.withTx(tx), userID, in, true)
	if err != nil {
		return EntryResult{}, err
	}
	if project != nil {
		if err := project(ctx, tx, res); err != nil {
			return EntryResult{}, err
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return EntryResult{}, fmt.Errorf("commit habit entry: %w", err)
	}
	return res, nil
}

func (s *service) recordEntry(
	ctx context.Context,
	store *Store,
	userID uuid.UUID,
	in EntryInput,
	lockHabit bool,
) (EntryResult, error) {
	var res EntryResult

	var h Habit
	var err error
	if lockHabit {
		h, err = store.habitForUpdate(ctx, userID, in.HabitID)
	} else {
		h, err = store.Habit(ctx, userID, in.HabitID)
	}
	if err != nil {
		return res, err
	}
	dateKey := in.DateKey
	if _, ok := ParseDay(dateKey); !ok {
		dateKey = DayKey(s.now())
	}
	now := s.now()
	nowMs := now.UnixMilli()
	id := EntryID(h.ID, dateKey)
	existing, found, err := store.Entry(ctx, userID, id)
	if err != nil {
		return res, err
	}

	if in.Op == OpUndo {
		if err := store.Tombstone(ctx, userID, EntityEntry, id, now); err != nil {
			return res, err
		}
		res.Removed = true
	} else {
		e := Entry{
			ID: id, HabitID: h.ID, DateKey: dateKey,
			Target: h.GoalTarget, CreatedAt: nowMs, UpdatedAt: nowMs,
		}
		if found {
			e.CreatedAt = existing.CreatedAt
		}
		switch in.Op {
		case OpSkip:
			e.Status = StatusSkipped
			e.SkipReason = strings.TrimSpace(in.Reason)
		case OpProgress:
			// A count/duration goal reaching its target IS a completion. Leaving it
			// "partial at 8/8" would mean the ring and the card disagreed about the
			// same habit.
			e.Value = in.Value
			if e.Value >= h.GoalTarget {
				e.Status = StatusDone
				e.Value = h.GoalTarget
				e.CompletedAt = nowMs
			} else {
				e.Status = StatusPartial
			}
		default:
			e.Status = StatusDone
			e.Value = h.GoalTarget
			e.CompletedAt = nowMs
		}
		if found && existing.Status == StatusDone && e.Status == StatusDone {
			e.CompletedAt = existing.CompletedAt
		}
		if found && sameEntryState(existing, e) {
			// Preserve the first semantic result. The projector still runs so a replay can
			// repair a gap left by the former best-effort REST implementation.
			res.Entry = &existing
		} else {
			written, err := store.Put(ctx, userID, EntityEntry, id, e, now)
			if err != nil {
				return res, err
			}
			if written {
				res.Entry = &e
			} else {
				// A newer device-clock version won last-write-wins. Project the actual row,
				// never the rejected REST intent.
				current, ok, err := store.Entry(ctx, userID, id)
				if err != nil {
					return res, err
				}
				if ok {
					res.Entry = &current
				} else {
					res.Removed = true
				}
			}
		}
	}

	entries, err := store.EntriesForHabit(ctx, userID, h.ID)
	if err != nil {
		return res, err
	}
	res.Stats = ComputeHabitStats(h, IndexEntries(entries).For(h.ID), s.resolveToday(dateKey))
	return res, nil
}

func sameEntryState(a, b Entry) bool {
	return a.ID == b.ID &&
		a.HabitID == b.HabitID &&
		a.DateKey == b.DateKey &&
		a.Status == b.Status &&
		a.Value == b.Value &&
		a.Target == b.Target &&
		a.SkipReason == b.SkipReason
}

func (s *service) AddNote(ctx context.Context, userID uuid.UUID, habitID, dateKey, text string) (Note, error) {
	text = strings.TrimSpace(text)
	if text == "" {
		return Note{}, ErrInvalidInput
	}
	if _, err := s.store.Habit(ctx, userID, habitID); err != nil {
		return Note{}, err
	}
	now := s.now()
	if _, ok := ParseDay(dateKey); !ok {
		dateKey = DayKey(now)
	}
	n := Note{
		ID:      uuid.NewString(),
		HabitID: habitID, DateKey: dateKey, Text: text,
		CreatedAt: now.UnixMilli(), UpdatedAt: now.UnixMilli(),
	}
	if _, err := s.store.Put(ctx, userID, EntityNote, n.ID, n, now); err != nil {
		return Note{}, err
	}
	return n, nil
}

func (s *service) DeleteNote(ctx context.Context, userID uuid.UUID, noteID string) error {
	return s.store.Tombstone(ctx, userID, EntityNote, noteID, s.now())
}
