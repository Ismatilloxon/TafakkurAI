func (s *service) Calendar(ctx context.Context, userID uuid.UUID, month, today string) (CalendarView, error) {
	snap, err := s.load(ctx, userID, today, WindowYear)
	if err != nil {
		return CalendarView{}, err
	}

	first := time.Date(snap.today.Year(), snap.today.Month(), 1, 0, 0, 0, 0, time.UTC)
	if month != "" {
		if t, err := time.Parse("2006-01", month); err == nil {
			first = t.UTC()
		}
	}
	out := CalendarView{Month: first.Format("2006-01")}

	// The month may fall outside the year window already loaded (the user paged back), so
	// its entries are fetched for exactly that range rather than widening every request.
	last := lastOfMonth(first)
	monthEntries, err := s.store.EntriesBetween(ctx, userID, DayKey(first), DayKey(last))
	if err != nil {
		return out, err
	}
	out.Days = RollDays(snap.all, IndexEntries(monthEntries), first, minTime(last, snap.today))
	out.MonthRate = Rate(out.Days)
	for _, d := range out.Days {
		if d.Perfect {
			out.PerfectDays++
		}
	}

	out.Streak, out.YearLongest = AccountStreak(snap.rolls)
	out.YearFrom = DayKey(dayFromNumber(dayNumber(snap.today) - WindowYear + 1))
	out.Year = make([]int, 0, len(snap.rolls))
	for _, r := range snap.rolls {
		out.Year = append(out.Year, r.Level)
		if r.Done > 0 {
			out.ActiveDays++
		}
	}
	return out, nil
}

func minTime(a, b time.Time) time.Time {
	if a.Before(b) {
		return a
	}
	return b
}

