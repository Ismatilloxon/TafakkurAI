/** 6,236 — the denominator for overall Qurʼan progress. Derived, never hardcoded. */
val TOTAL_AYAH_COUNT: Int = SURAH_CATALOG.sumOf { it.ayahCount }

private val bySurahNumber: Map<Int, Surah> = SURAH_CATALOG.associateBy { it.number }

fun surahOf(number: Int): Surah? = bySurahNumber[number]

fun ayahCountOf(surahNumber: Int): Int = bySurahNumber[surahNumber]?.ayahCount ?: 0
